import assert from 'node:assert/strict'
import { mkdir, mkdtemp, readFile, readdir, stat, symlink, writeFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { test } from 'node:test'
import {
  assertManagedFile,
  copyVerified,
  exists,
  hashFile,
  managedDirectory,
  syncFile
} from './files'

async function workspace(): Promise<string> {
  const root = process.env.ARKIVE_TEST_ROOT ?? join(homedir(), 'Desktop', 'arkive-test')
  await mkdir(root, { recursive: true })
  return mkdtemp(join(root, 'catalog-files-'))
}

void test('sync flushes existing data without changing bytes, timestamps or creating missing files', async () => {
  const root = await workspace()
  const input = join(root, 'sync.txt')
  await writeFile(input, 'durable generated fixture')
  const before = await stat(input)
  await syncFile(input)
  assert.equal(await readFile(input, 'utf8'), 'durable generated fixture')
  assert.equal((await stat(input)).mtimeMs, before.mtimeMs)
  const missing = join(root, 'missing.txt')
  await assert.rejects(syncFile(missing))
  assert.equal(await exists(missing), false)
})

void test('verified publication preserves bytes, removes staging and refuses conflicting outputs', async () => {
  const root = await workspace()
  const input = join(root, 'source.txt')
  const target = join(root, 'published.txt')
  await writeFile(input, 'verified generated bytes')
  const hash = await hashFile(input)
  await copyVerified(input, target, hash)
  assert.equal(await hashFile(target), hash)
  assert.equal(await hashFile(input), hash)
  assert.equal(await exists(`${target}.partial`), false)
  await copyVerified(input, target, hash)
  await writeFile(target, 'outside edit')
  await assert.rejects(copyVerified(input, target, hash), /目标已存在/)
  assert.equal(await readFile(target, 'utf8'), 'outside edit')
})

void test('managed paths accept real descendants and platform-correct case variants', async () => {
  const root = join(await workspace(), 'Archive')
  const date = await managedDirectory(root, '2000-01-01')
  const file = join(date, '中文.txt')
  await writeFile(file, 'generated managed fixture')
  await assertManagedFile(root, file)
  if (process.platform === 'win32') await assertManagedFile(root.toUpperCase(), file.toUpperCase())
})

void test('managed paths reject siblings/traversal without creating directories in the archive', async () => {
  const directory = await workspace()
  const root = await managedDirectory(join(directory, 'Archive'))
  const outside = join(directory, 'Archive-sibling', 'outside-date')
  await mkdir(outside, { recursive: true })
  const file = join(outside, 'retained.txt')
  await writeFile(file, 'retained outside archive')
  const before = await readdir(root)
  await assert.rejects(assertManagedFile(root, file), /文件已离开受管理目录/)
  assert.deepEqual(await readdir(root), before)
  assert.equal(await readFile(file, 'utf8'), 'retained outside archive')
})

void test(
  'managed paths reject parent junction aliases',
  { skip: process.platform !== 'win32' },
  async () => {
    const directory = await workspace()
    const root = await managedDirectory(join(directory, 'Archive'))
    const outside = join(directory, 'outside')
    await mkdir(outside)
    await writeFile(join(outside, 'retained.txt'), 'unchanged outside fixture')
    const alias = join(root, '2000-01-01')
    await symlink(outside, alias, 'junction')
    await assert.rejects(assertManagedFile(root, join(alias, 'retained.txt')))
    assert.equal(await readFile(join(outside, 'retained.txt'), 'utf8'), 'unchanged outside fixture')
  }
)
